"""Emit CREATE DDL for every SQLAlchemy entity (PostgreSQL dialect) without touching a DB.

Usage (from backend/):  PYTHONPATH=. .venv/Scripts/python db/dump_ddl.py > db/migrations/001_init_schema.sql
"""
import importlib
import pathlib
import sys

import app
from app.db.base import Base
from sqlalchemy import create_mock_engine
from sqlalchemy import Enum as PgEnum

# Feature packages have no __init__.py, so walk the files instead of pkgutil.
root = pathlib.Path(app.__file__).parent
for f in sorted(root.glob("*/entities/*.py")):
    importlib.import_module(".".join(f.relative_to(root.parent).with_suffix("").parts))

out: list[str] = []


def dump(sql, *a, **kw):
    out.append(str(sql.compile(dialect=engine.dialect)).strip() + ";\n")


engine = create_mock_engine("postgresql+psycopg://", dump)

# pg_enum() binds with create_type=False, so emit the enum types ourselves.
enums: dict[str, tuple[str, ...]] = {}
for table in Base.metadata.tables.values():
    for col in table.columns:
        if isinstance(col.type, PgEnum):
            enums[col.type.name] = tuple(col.type.enums)

header = ["-- GENERATED by db/dump_ddl.py from app/*/entities -- do not hand-edit.\n"]
header += [
    f"CREATE TYPE {name} AS ENUM ({', '.join(repr(v) for v in values)});\n"
    for name, values in sorted(enums.items())
]

Base.metadata.create_all(engine, checkfirst=False)
sys.stdout.write("\n".join(header + out))
